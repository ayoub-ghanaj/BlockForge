"""Export the same immutable block snapshot into all three formats."""

import gzip
import math
import struct
import time
import zlib
from collections import Counter
from pathlib import Path

from . import nbt
from .palette import canonical_state
from .shapes import orientations, with_properties


def validate_profile(build, profile):
    """Reject a snapshot whose version or states differ from its selected preset."""
    if build.get("version") != profile.id or build["data_version"] != profile.data_version:
        raise ValueError("Preview version differs from the selected preset; regenerate it")
    allowed = set()
    for block in profile.blocks:
        for state, _ in orientations(block):
            allowed.add(state)
            if block.shape == "stairs":
                for corner in ("inner_left", "inner_right", "outer_left", "outer_right"):
                    allowed.add(with_properties(state, shape=corner))
    unknown = set(build["palette"]) - allowed
    if unknown:
        raise ValueError(
            f"Preview contains states outside Minecraft {profile.id}: {sorted(unknown)[0]}"
        )


def validate_build(build):
    size = build["size"]
    if len(size) != 3 or any(type(v) is not int or not 1 <= v <= 512 for v in size):
        raise ValueError("Invalid build dimensions")
    if math.prod(size) > 2_000_000:
        raise ValueError("Build exceeds two million cells")
    version = build["data_version"]
    if type(version) is not int or version < 0:
        raise ValueError("Invalid Minecraft data version")
    palette = build["palette"]
    for state in palette:
        canonical_state(state)
    if (
        not palette
        or len(set(palette)) != len(palette)
        or any(s.split("[")[0] in ("minecraft:air", "minecraft:void_air") for s in palette)
    ):
        raise ValueError("Build palette must contain unique, non-air states")
    seen = set()
    for x, y, z, index in build["cells"]:
        if any(type(v) is not int for v in (x, y, z, index)) or not (
            0 <= x < size[0] and 0 <= y < size[1] and 0 <= z < size[2] and 0 <= index < len(palette)
        ):
            raise ValueError("Block outside the build bounds or palette")
        if (x, y, z) in seen:
            raise ValueError("Multiple blocks occupy the same position")
        seen.add((x, y, z))


def dense(build):
    xsize, ysize, zsize = build["size"]
    values = [0] * (xsize * ysize * zsize)
    for x, y, z, index in build["cells"]:
        values[x + xsize * (z + zsize * y)] = index + 1
    return values


def varints(values):
    result = bytearray()
    for value in values:
        while value >= 128:
            result.append((value & 127) | 128)
            value >>= 7
        result.append(value)
    return bytes(result)


def schematic(build, name, author):
    x, y, z = build["size"]
    palette = ["minecraft:air"] + build["palette"]
    root = {
        "Version": (3, 2),
        "DataVersion": (3, build["data_version"]),
        "Width": (2, x),
        "Height": (2, y),
        "Length": (2, z),
        "Offset": (11, [0, 0, 0]),
        "PaletteMax": (3, len(palette)),
        "Palette": (10, {s: (3, i) for i, s in enumerate(palette)}),
        "BlockData": (7, varints(dense(build))),
        "BlockEntities": (9, (10, [])),
        "Entities": (9, (10, [])),
        "Metadata": (
            10,
            {"Name": (8, name), "Author": (8, author), "Date": (4, int(time.time() * 1000))},
        ),
    }
    return gzip.compress(nbt.encode(root, "Schematic"), mtime=0)


def litematic(build, name, author):
    palette = ["minecraft:air"] + build["palette"]
    region = {
        "Position": (10, nbt.compound_xyz((0, 0, 0))),
        "Size": (10, nbt.compound_xyz(build["size"])),
        "BlockStatePalette": (9, (10, [nbt.block_state(s) for s in palette])),
        "BlockStates": (12, nbt.pack_bits(dense(build), max(2, (len(palette) - 1).bit_length()))),
        "TileEntities": (9, (10, [])),
        "Entities": (9, (10, [])),
        "PendingBlockTicks": (9, (10, [])),
        "PendingFluidTicks": (9, (10, [])),
    }
    now = int(time.time() * 1000)
    meta = {
        "Name": (8, name),
        "Author": (8, author),
        "Description": (8, "Generated by Minecraft Builder for Blender"),
        "RegionCount": (3, 1),
        "TimeCreated": (4, now),
        "TimeModified": (4, now),
        "TotalBlocks": (3, len(build["cells"])),
        "TotalVolume": (3, math.prod(build["size"])),
        "EnclosingSize": (10, nbt.compound_xyz(build["size"])),
    }
    # v5 block storage remains supported by modern Litematica and older readers.
    root = {
        "Version": (3, 5),
        "SubVersion": (3, 1),
        "MinecraftDataVersion": (3, build["data_version"]),
        "Metadata": (10, meta),
        "Regions": (10, {"Build": (10, region)}),
    }
    return gzip.compress(nbt.encode(root), mtime=0)


def thumbnail(build):
    """Small PNG top view, no imaging dependency and no external assets."""
    width = height = 128
    pixels = bytearray([35, 39, 46, 255]) * (width * height)
    top = {}
    for x, y, z, index in build["cells"]:
        if (x, z) not in top or y > top[(x, z)][0]:
            top[x, z] = (y, index)
    for py in range(height):
        for px in range(width):
            x = min(build["size"][0] - 1, px * build["size"][0] // width)
            z = min(build["size"][2] - 1, py * build["size"][2] // height)
            if (x, z) in top:
                rgb = build.get("colors", [[170, 170, 170]] * len(build["palette"]))[top[x, z][1]]
                i = (py * width + px) * 4
                pixels[i : i + 4] = bytes([*rgb, 255])
    scan = b"".join(b"\0" + pixels[y * width * 4 : (y + 1) * width * 4] for y in range(height))

    def chunk(kind, data):
        return (
            struct.pack(">I", len(data))
            + kind
            + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(scan))
        + chunk(b"IEND", b"")
    )


def blueprint(build, name, author):
    # Empty bounding cells are AIR, while padding beyond bounds is VOID_AIR.
    # This distinction preserves hollow builds when pasted over existing blocks.
    palette = ["minecraft:void_air", "minecraft:air"] + build["palette"]
    by_section = {}
    sx, sy, sz = build["size"]
    for cy in range((sy + 15) // 16):
        for cz in range((sz + 15) // 16):
            for cx in range((sx + 15) // 16):
                values = [0] * 4096
                for y in range(min(16, sy - cy * 16)):
                    for z in range(min(16, sz - cz * 16)):
                        for x in range(min(16, sx - cx * 16)):
                            values[x + 16 * z + 256 * y] = 1
                by_section[cx, cy, cz] = values
    for x, y, z, index in build["cells"]:
        by_section[x // 16, y // 16, z // 16][(x % 16) + 16 * (z % 16) + 256 * (y % 16)] = index + 2
    sections = []
    for (x, y, z), values in sorted(by_section.items()):
        used = sorted(set(values))
        remap = {old: i for i, old in enumerate(used)}
        states = {"palette": (9, (10, [nbt.block_state(palette[i]) for i in used]))}
        if len(used) > 1:
            states["data"] = (
                12,
                nbt.pack_bits(
                    [remap[i] for i in values], max(4, (len(used) - 1).bit_length()), padded=True
                ),
            )
        sections.append({"X": (3, x), "Y": (3, y), "Z": (3, z), "BlockStates": (10, states)})
    header = nbt.encode(
        {
            "Version": (3, 2),
            "Name": (8, name),
            "Author": (8, author),
            "Tags": (9, (8, ["Blender"])),
            "ThumbnailYaw": (5, 135.0),
            "ThumbnailPitch": (5, 30.0),
            "LockedThumbnail": (1, 1),
            "BlockCount": (3, len(build["cells"])),
            "ContainsAir": (1, len(build["cells"]) < math.prod(build["size"])),
        }
    )
    png = thumbnail(build)
    blocks = gzip.compress(
        nbt.encode(
            {
                "DataVersion": (3, build["data_version"]),
                "BlockRegion": (9, (10, sections)),
                "BlockEntities": (9, (10, [])),
                "Entities": (9, (10, [])),
            }
        ),
        mtime=0,
    )
    return (
        struct.pack(">I", 0x0AE5BB36)
        + struct.pack(">I", len(header))
        + header
        + struct.pack(">I", len(png))
        + png
        + struct.pack(">I", len(blocks))
        + blocks
    )


def write(path, build, kind, name="Blender build", author=""):
    validate_build(build)
    data = {"schem": schematic, "litematic": litematic, "bp": blueprint}[kind](build, name, author)
    path = Path(path)
    # Construct everything before touching the destination, then replace atomically.
    import os
    import tempfile

    fd, temporary = tempfile.mkstemp(prefix="." + path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def material_counts(build):
    return Counter(build["palette"][index].split("[")[0] for *_, index in build["cells"])
